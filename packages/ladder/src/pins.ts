import { existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import {
  DECISION_POINT_PINS,
  DECISION_POINTS,
  POINT_THRESHOLDS,
  THRESHOLD_PINS,
} from "@intelligence/contracts/personal";
import { hashOf } from "./hash.ts";

// The contracts' pinned history, generated from what it pins, since the contracts import nothing:
// the decision points and their thresholds here, the prompts' text by pi's extract/prompt-pins.ts.
// A pin, once made, stays: the history keeps every pin in its order and adds a new version's after
// it, and a value that no longer hashes to its pin is refused, never re-pinned. Run
// `node packages/ladder/src/pins.ts` after adding a point version; pins.test.ts fails
// while the file and the definitions differ. Reads the contracts and the hash alone, never the
// registry, which refuses to load a definition before its pin is made.

// A file of the personal contracts, from the repository's root, found as personal-core's repoRoot
// finds it (the ladder imports the contracts alone).
export function contractsFile(name: string): string {
  for (let dir = import.meta.dirname; dirname(dir) !== dir; dir = dirname(dir))
    if (existsSync(join(dir, "pnpm-workspace.yaml")))
      return join(dir, "packages", "contracts", "src", "personal", name);
  throw new Error("no pnpm-workspace.yaml above the code");
}
export const POINT_PINS_FILE = contractsFile("point-pins.generated.ts");

// The history with the new pins after it. A pin the code moved is refused by name.
export function pinHistory(
  pinned: Readonly<Record<string, string>>,
  code: ReadonlyMap<string, string>,
): [string, string][] {
  const moved = [...code]
    .filter(([key, hash]) => pinned[key] !== undefined && pinned[key] !== hash)
    .map(([key]) => key);
  if (moved.length > 0) throw new Error(`moved under its pin: ${moved.join(", ")}`);
  return [...Object.entries(pinned), ...[...code].filter(([key]) => pinned[key] === undefined)];
}

// A generated file of frozen `<id>@<version>` to hash constants, by name.
export const pinsSource = (by: string, constants: readonly [string, readonly [string, string][]][]): string =>
  [
    `// Generated by \`node ${by}\`: never edit by hand.`,
    ...constants.flatMap(([name, entries]) => [
      `export const ${name} = Object.freeze({`,
      ...entries.map(([key, hash]) => `  "${key}": "${hash}",`),
      "});",
    ]),
    "",
  ].join("\n");

export const pointPinsSource = (): string =>
  pinsSource("packages/ladder/src/pins.ts", [
    [
      "PINNED_POINTS",
      pinHistory(DECISION_POINT_PINS, new Map(DECISION_POINTS.map((one) => [`${one.id}@${one.version}`, hashOf(one)]))),
    ],
    [
      "PINNED_THRESHOLDS",
      pinHistory(THRESHOLD_PINS, new Map(Object.entries(POINT_THRESHOLDS).map(([key, one]) => [key, hashOf(one)]))),
    ],
  ]);

if (import.meta.main) writeFileSync(POINT_PINS_FILE, pointPinsSource());
